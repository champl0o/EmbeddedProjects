static void setLed(int pin, uint8_t brightness)
{
  ledcWrite(pin, pgm_read_byte(&gamma8[brightness]));
}

void ledDriverBegin()
{
  for (int i = 0; i < N; i++)
  {
    ledcAttach(RED_PINS[i],  PWM_FREQ, PWM_RES);
    ledcAttach(BLUE_PINS[i], PWM_FREQ, PWM_RES);
  }
}

void applyFrame(const uint8_t *frame)
{
  for (int i = 0; i < N; i++)
  {
    setLed(RED_PINS[i],  frame[i]);
    setLed(BLUE_PINS[i], frame[i + N]);
  }
}
